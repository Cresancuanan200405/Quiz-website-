export const guessWordQuestionSectionsByCount: Record<number, Difficulty> = {
  10: "Easy",
  15: "Medium",
  20: "Medium",
  25: "Hard",
  30: "Hard",
};

export const getGuessWordBankQuestions = (category: string, count: number): Question[] => {
  const categoryQuestions = guessWordQuestionsByCategory[category as QuizCategory] ?? [];
  const expectedDifficulty = guessWordQuestionSectionsByCount[count] ?? null;
  if (!expectedDifficulty) return categoryQuestions.slice(0, count);
  const sectionQuestions = categoryQuestions.filter((question) => question.difficulty === expectedDifficulty);
  if (sectionQuestions.length >= count) return sectionQuestions.slice(0, count);
  return categoryQuestions.slice(0, count);
};
