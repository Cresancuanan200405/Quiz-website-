export const rapidFireQuestionsByCategory: Record<QuizCategory, Question[]> = {
  Science: rapidFireQuestions.filter((question) => question.category === "Science"),
  History: rapidFireQuestions.filter((question) => question.category === "History"),
  Tech: rapidFireQuestions.filter((question) => question.category === "Tech"),
  Nature: rapidFireQuestions.filter((question) => question.category === "Nature"),
  Arts: rapidFireQuestions.filter((question) => question.category === "Arts"),
  Anime: rapidFireQuestions.filter((question) => question.category === "Anime"),
  Food: rapidFireQuestions.filter((question) => question.category === "Food"),
  Animals: rapidFireQuestions.filter((question) => question.category === "Animals"),
  Business: rapidFireQuestions.filter((question) => question.category === "Business"),
};

export const rapidFireQuestionSectionsByCount: Record<number, Difficulty> = {
  10: "Easy",
  15: "Medium",
  20: "Medium",
  25: "Hard",
  30: "Hard",
};

export const getRapidFireBankQuestions = (category: string, count: number): Question[] => {
  const categoryQuestions = rapidFireQuestionsByCategory[category as QuizCategory] ?? [];
  const expectedDifficulty = rapidFireQuestionSectionsByCount[count] ?? null;
  if (!expectedDifficulty) return categoryQuestions.slice(0, count);
  const sectionQuestions = categoryQuestions.filter((question) => question.difficulty === expectedDifficulty);
  if (sectionQuestions.length >= count) return sectionQuestions.slice(0, count);
  return categoryQuestions.slice(0, count);
};
